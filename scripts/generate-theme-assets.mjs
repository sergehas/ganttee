// Embeds every media/themes/*.json asset into a generated webview module; registry rules live in chartThemes.ts.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const themesDir = path.join(root, "media", "themes");
const outputFile = path.join(
  root,
  "src",
  "webview",
  "features",
  "chart",
  "themes",
  "themeAssets.generated.ts",
);

const assets = readdirSync(themesDir)
  .filter((fileName) => fileName.endsWith(".json"))
  .sort()
  .map((fileName) => ({
    fileName,
    data: JSON.parse(readFileSync(path.join(themesDir, fileName), "utf8")),
  }));

const source = `// Generated by scripts/generate-theme-assets.mjs. Do not edit.
import type { ThemeAsset } from "@webview/features/chart/themes/chartThemes";

/** Theme assets bundled from \`media/themes\`. */
export const THEME_ASSETS: readonly ThemeAsset[] = ${JSON.stringify(assets, null, 2)};
`;

mkdirSync(path.dirname(outputFile), { recursive: true });
writeFileSync(outputFile, source);
